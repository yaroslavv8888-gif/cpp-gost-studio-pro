import assert from 'node:assert/strict';
import {buildFlowFromCpp} from './src/engine/cppParserAndBuilder';
import {getEdgePoints} from './src/engine/orthoRouter';
import type {FlowNode,FlowEdge} from './src/types/flow';
const options={exampleStyle:true,showKeywords:true,gostLoopBounds:false,groupStmts:true,gostNumbers:false,autoSyncCpp:true};
const graph=buildFlowFromCpp('int main(){return 0;}',options);
const terminal=graph.nodes.find(n=>n.text==='return 0;')!;
assert.equal(terminal.type,'terminator','Final return must be an oval');
assert.equal(graph.edges.filter(e=>e.from===terminal.id).length,0,'Nothing may follow final return');
assert.ok(!graph.nodes.some(n=>n.text==='Конец'),'No extra End after return');
assert.ok(graph.nodes.some(n=>n.type==='brace'&&n.text==='}'&&n.y>=terminal.y+terminal.h),'Closing brace must be below oval');
const ret:FlowNode={id:'r',type:'process',text:'return 0;',cx:100,y:0,w:150,h:54};
const join:FlowNode={id:'j',type:'connector',text:'',cx:100,y:120,w:2,h:2};
const exit:FlowEdge={id:'e',from:'r',to:'j',fromEdge:null,toEdge:null,fromPort:'bottom',toPort:'right',leftLabel:'',rightLabel:'',style:'bypass_right',bendOffset:0};
const points=getEdgePoints([ret,join],[exit],exit)!;
assert.ok(points.every(p=>p.x===ret.cx),'Clear return path must be vertical');
const blocked={...ret,id:'obstacle',text:'work();',w:30,h:10,y:ret.y+ret.h+12};
assert.ok(getEdgePoints([ret,join,blocked],[exit],exit)!.some(p=>p.x!==ret.cx),'Obstructed return keeps bypass');
const manual={...exit,waypoints:[{x:300,y:64},{x:300,y:100}]};
assert.ok(getEdgePoints([ret,join],[manual],manual)!.some(p=>p.x===300),'Explicit user bends remain intact');
console.log('Return oval, final brace, straight paths and bypass regressions passed.');
