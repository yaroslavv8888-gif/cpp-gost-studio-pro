import assert from 'node:assert/strict';
import { FlowNode, FlowEdge, CodeGenOptions } from './src/types/flow';
import { normalizeFlowJunctions, alignedEdges } from './src/engine/graphEditing';
import { getEdgePoints, getLineAnchor, getLineAnchorPoint } from './src/engine/orthoRouter';
import { buildFlowFromCpp, synthesizeCppFromGraph } from './src/engine/cppParserAndBuilder';
const n=(id:string,cx:number,y:number):FlowNode=>({id,type:'process',text:'x++;',cx,y,w:80,h:40});
const e=(id:string,from:string,to:string):FlowEdge=>({id,from,to,fromEdge:null,toEdge:null,fromPort:'bottom',toPort:'top',style:'ortho',bendOffset:0,leftLabel:'',rightLabel:''});
const nodes=[n('a',0,0),n('b',200,0),{...n('j',100,120),type:'connector' as const,text:'1',w:44,h:44},n('c',100,240)];
const edges=[e('a','a','j'),e('b','b','j'),e('c','j','c')];
const normalized=normalizeFlowJunctions(nodes,edges);
assert.equal(normalized[2].text,'');assert.equal(normalized[2].w,2);assert.equal(normalized[2].y+normalized[2].h/2,142);
assert.deepEqual(normalizeFlowJunctions(normalized,edges),normalized);
assert.deepEqual(normalizeFlowJunctions(nodes,edges.slice(1)),nodes,'explicit numbered reference is preserved');
for(const edge of edges.slice(0,2)) assert.deepEqual(getEdgePoints(normalized,edges,edge)!.at(-1),{x:100,y:142});
const parent=e('parent','a','c');
const pts=getEdgePoints(normalized,[parent],parent)!;
const requested={x:pts[0].x+(pts[1].x-pts[0].x)*0.2,y:pts[0].y+(pts[1].y-pts[0].y)*0.2};
const anchor=getLineAnchor(pts,requested);
const branch={...e('branch','b',''),to:null,toEdge:'parent',toPort:'edge' as const,toAnchor:anchor};
assert.deepEqual(getEdgePoints(normalized,[parent,branch],branch)!.at(-1),requested,'attachment stays at clicked position');
const moved=normalized.map(n=>n.id==='c'?{...n,y:340}:n);
const movedParent=getEdgePoints(moved,[parent,branch],parent)!;
assert.deepEqual(getEdgePoints(moved,[parent,branch],branch)!.at(-1),getLineAnchorPoint(movedParent,anchor));
const sourceBranch={...e('source','','b'),from:null,fromEdge:'parent',fromPort:'edge' as const,fromAnchor:anchor};
assert.deepEqual(getEdgePoints(normalized,[parent,sourceBranch],sourceBranch)![0],requested,'branch starts at clicked position');
const old=[n('top',100,0),n('bottom',104,140),n('other',300,20)];
const stale={...e('stale','top','bottom'),waypoints:[{x:104,y:80},{x:104,y:100}],bendOffset:4};
const unaffected={...e('other','other','other'),waypoints:[{x:400,y:100}]};
const aligned=old.map(n=>n.id==='bottom'?{...n,cx:100}:n);
const refreshed=alignedEdges(old,aligned,[stale,unaffected]);
assert.deepEqual(getEdgePoints(aligned,refreshed,refreshed[0]),[{x:100,y:40},{x:100,y:140}],'alignment removes stair step');
assert.equal(refreshed[1],unaffected,'unrelated manual route remains intact');
const options:CodeGenOptions={exampleStyle:true,showKeywords:true,gostLoopBounds:false,groupStmts:false,gostNumbers:false,autoSyncCpp:true};
const g=buildFlowFromCpp('int main(){int j=3;while(j>0){if(j>1){j--;}else{j=0;}}return 0;}',options);
const saved=g.nodes.map(n=>n.type==='connector'?{...n,text:'1',w:44,h:44,y:n.y+n.h/2-22}:n);
assert.equal(synthesizeCppFromGraph(normalizeFlowJunctions(saved,g.edges),g.edges).code,synthesizeCppFromGraph(g.nodes,g.edges).code,'junction migration preserves C++');
console.log('Line junctions, exact anchors, moving parents, alignment and reverse C++ passed.');
